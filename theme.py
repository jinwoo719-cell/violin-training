#      주황    ∨ 업보우
#      초록    맞았음 · 1포지션
#      장미    틀렸음 · 짚을 손끝
#      호박    박자 주의   ← 골드보다 밝고 진합니다. 헷갈리면 안 되니까.
#      청록    활 흔들림   ← 위 어느 것과도 안 겹치는 자리
