def place(glyph, x, y, height, fill, anchor="center"):
    """기호 하나를 (x, y) 에 높이 height 로 놓습니다.

    anchor="center"    세로 가운데를 y 에 맞춤 (임시표·조표)
    anchor="baseline"  글꼴의 기준선을 y 에 맞춤 (자리표 — 나선 중심이 여기)
    """
    #| 흐름  글꼴 좌표를 화면 좌표로 옮기고 크기를 맞춘다
    #| 입력  기호 · 놓을 자리 · 높이
    #| 단계  경계 상자의 높이로 배율을 구한다
    #| 갈래  가운데 맞춤인가 ? 경계 상자의 중심만큼 올린다 : 기준선을 그대로 쓴다
    #| 단계  글꼴은 y가 위로 가므로 세로를 뒤집는다
    #| 출력  <g><path/></g> 한 조각
    x0, y0, x1, y1, d = glyph
    s = height / (y1 - y0)
    dy = -(y0 + y1) / 2 * s if anchor == "center" else 0.0
    return (f'<g transform="translate({x - x0 * s:.2f},{y + dy:.2f}) '
            f'scale({s:.5f},{-s:.5f})"><path d="{d}" fill="{fill}"/></g>')


def width_of(glyph, height):
    """그 높이로 그렸을 때의 가로 폭 (다음 기호를 어디에 놓을지 정할 때)"""
    x0, y0, x1, y1, _ = glyph
    return (x1 - x0) * height / (y1 - y0)
